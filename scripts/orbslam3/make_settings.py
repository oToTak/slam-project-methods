#!/usr/bin/env python3
"""Generate the ORB-SLAM3 settings files for the UCU dataset from configs/orbslam3/ucu_calib.json.

  python scripts/orbslam3/make_settings.py --write      # (re)write configs/orbslam3/UCU_mono.yaml and UCU_mono_inertial.yaml
  python scripts/orbslam3/make_settings.py --check      # exit 1 if the committed files differ from what would be generated
  python scripts/orbslam3/make_settings.py --mode mono_inertial          # print to stdout

Format: ORB-SLAM3 'File.version: "1.0"' settings (src/Settings.cc @4452a3c). Keys, their types and which are mandatory
were read from that source, not from memory: float keys must be written as reals ('125.0', not '125'), ints as ints,
IMU.T_b_c1 must carry 'dt: f' like the upstream examples (the parser does not check the type tag).

Camera-IMU transform (the point that is easy to get wrong):
  Kalibr camchain-imucam.yaml: T_cam_imu = T_ci maps IMU coordinates into the camera frame (IMU -> camera).
  The dataset's calibration.yaml stores the same numbers under the name T_base_color (looks like base<-color): the naming
  is inverted (old-dvpo/CONVENTIONS.md). ORB-SLAM3 'IMU.T_b_c1' = pose of the camera in the body (IMU) frame
  = T_b_c = T_ic = inverse(T_ci):   R_ic = R_ci^T,   t_ic = -R_ci^T t_ci.
  The body frame is the IMU frame (dataset: T_base_imu = identity).
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import orb3_lib as lib  # noqa: E402

CONFIG_DIR = lib.REPO_ROOT / "configs" / "orbslam3"
FILES = {"mono": CONFIG_DIR / "UCU_mono.yaml", "mono_inertial": CONFIG_DIR / "UCU_mono_inertial.yaml"}

# One configuration for all sequences (CLAUDE_teodor.md). Values = ORB-SLAM3 upstream examples (Examples/Monocular/TUM1.yaml,
# Examples/Monocular-Inertial/EuRoC.yaml); nothing here was tuned on UCU data.
ORB_PARAMS = [("nFeatures", 1000), ("scaleFactor", 1.2), ("nLevels", 8), ("iniThFAST", 20), ("minThFAST", 7)]
VIEWER = [("KeyFrameSize", 0.05), ("KeyFrameLineWidth", 1.0), ("GraphLineWidth", 0.9), ("PointSize", 2.0),
          ("CameraSize", 0.08), ("CameraLineWidth", 3.0), ("ViewpointX", 0.0), ("ViewpointY", -0.7),
          ("ViewpointZ", -1.8), ("ViewpointF", 500.0)]  # unused (viewer is off) but mandatory keys


def t_b_c(cal):
    """Camera -> body (IMU) transform for IMU.T_b_c1: inverse of Kalibr T_cam_imu (see module docstring)."""
    return lib.se3_inverse(cal["T_cam_imu"])


def render(cal, mode, use_t_ci=False):
    if mode not in FILES:
        raise ValueError(f"mode must be one of {sorted(FILES)}")
    c, fmt = cal["camera"], lib.fmt_real
    w, h = cal["resolution"]
    L = []
    add = L.append
    add("%YAML:1.0")
    add("")
    add("# GENERATED by scripts/orbslam3/make_settings.py from configs/orbslam3/ucu_calib.json: do not edit by hand")
    add("# (python scripts/orbslam3/make_settings.py --write). ORB-SLAM3 4452a3c 'File.version 1.0' format.")
    add(f"# Mode: {mode}. Calibration source: UCU SLAM Dataset v1 Kalibr results (see ucu_calib.json).")
    add("")
    add("#--------------------------------------------------------------------------------------------")
    add("# Camera (RealSense D435 colour stream, radtan; the driver feeds the RAW distorted images)")
    add("#--------------------------------------------------------------------------------------------")
    add('File.version: "1.0"')
    add("")
    add('Camera.type: "PinHole"')
    for k in ("fx", "fy", "cx", "cy", "k1", "k2", "p1", "p2"):
        add(f"Camera1.{k}: {fmt(c[k])}")
    add("")
    add(f"Camera.width: {int(w)}")
    add(f"Camera.height: {int(h)}")
    add(f"Camera.fps: {int(cal['fps'])}")
    add("# Colour order of the images the driver passes (cv::imread gives BGR). Ignored for grayscale.")
    add("Camera.RGB: 0")
    if mode == "mono_inertial":
        im = cal["imu"]
        T = cal["T_cam_imu"] if use_t_ci else t_b_c(cal)       # use_t_ci: ABLATION ONLY (dataset T_base_color taken at face value)
        add("")
        add("#--------------------------------------------------------------------------------------------")
        add("# IMU (Phidgets 1042, 125 Hz). Body frame = IMU frame.")
        add("#--------------------------------------------------------------------------------------------")
        add("# Camera -> body (IMU) transform = Kalibr T_ic = inverse(T_cam_imu). See make_settings.py docstring.")
        add("IMU.T_b_c1: !!opencv-matrix")
        add("   rows: 4")
        add("   cols: 4")
        add("   dt: f")
        rows = [", ".join(fmt(v) for v in T[i]) for i in range(4)]
        add(f"   data: [{rows[0]},")
        add(f"         {rows[1]},")
        add(f"         {rows[2]},")
        add(f"         {rows[3]}]")
        add("")
        add("# Kalibr continuous-time densities used AS IS (ORB-SLAM3 multiplies by sqrt(IMU.Frequency) itself).")
        add("# TODO(verify): Kalibr densities are often optimistic for real sensors; if initialisation is unstable consider")
        add("# a larger value, but only as a documented new run (one config for all sequences).")
        add(f"IMU.NoiseGyro: {fmt(im['gyroscope_noise_density'])}")
        add(f"IMU.NoiseAcc: {fmt(im['accelerometer_noise_density'])}")
        add(f"IMU.GyroWalk: {fmt(im['gyroscope_random_walk'])}")
        add(f"IMU.AccWalk: {fmt(im['accelerometer_random_walk'])}")
        add(f"IMU.Frequency: {fmt(im['rate_hz'])}")
    add("")
    add("#--------------------------------------------------------------------------------------------")
    add("# ORB extractor (upstream example values, not tuned)")
    add("#--------------------------------------------------------------------------------------------")
    for k, v in ORB_PARAMS:
        add(f"ORBextractor.{k}: {v if isinstance(v, int) else fmt(v)}")
    add("")
    add("#--------------------------------------------------------------------------------------------")
    add("# Viewer (the driver runs headless; keys are still mandatory in Settings.cc)")
    add("#--------------------------------------------------------------------------------------------")
    for k, v in VIEWER:
        add(f"Viewer.{k}: {fmt(v)}")
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--calib", type=Path, default=lib.DEFAULT_CALIB)
    ap.add_argument("--mode", choices=sorted(FILES) + ["all"], default="all")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true", help="write configs/orbslam3/UCU_<mode>.yaml")
    g.add_argument("--check", action="store_true", help="exit 1 if committed files differ from the generated text")
    ap.add_argument("--out", type=Path, help="with a single --mode: write there instead of stdout")
    ap.add_argument("--ablation-use-t-ci", action="store_true",
                    help="ABLATION ONLY (stdout/--out, never --write): put T_cam_imu itself (= the dataset's T_base_color) into "
                         "IMU.T_b_c1 to test the claim that the dataset extrinsics are inverted")
    args = ap.parse_args(argv)
    cal = lib.load_calibration(args.calib)
    if args.ablation_use_t_ci and (args.write or args.check):
        ap.error("--ablation-use-t-ci cannot be combined with --write/--check")
    modes = sorted(FILES) if args.mode == "all" else [args.mode]
    rc = 0
    for m in modes:
        text = render(cal, m, args.ablation_use_t_ci)
        if args.write:
            with open(FILES[m], "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
            print(f"wrote {FILES[m]}")
        elif args.check:
            have = FILES[m].read_text(encoding="utf-8").replace("\r\n", "\n") if FILES[m].exists() else None
            if have != text:
                print(f"DIFFERS: {FILES[m]} (run: python scripts/orbslam3/make_settings.py --write)")
                rc = 1
            else:
                print(f"ok: {FILES[m]}")
        elif args.out and len(modes) == 1:
            with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
        else:
            sys.stdout.write(text)
    return rc


if __name__ == "__main__":
    sys.exit(main())
